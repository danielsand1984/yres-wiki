/* ------------------------------------------------------------------ */
/*  Auto-append pages that aren't placed in the curated sidebar above  */
/*  (e.g. freshly created via the CMS) under an "Overig / More" group.  */
/* ------------------------------------------------------------------ */

/** Collect explicit doc-ids and autogenerated dirNames from the curated tree. */
function scanCurated(items, ids, autogenDirs) {
  for (const item of items) {
    if (typeof item === 'string') {
      ids.add(item);
    } else if (item && typeof item === 'object') {
      if (item.type === 'autogenerated' && item.dirName) {
        autogenDirs.add(item.dirName.replace(/\/+$/, ''));
      }
      if (item.link && item.link.type === 'doc' && item.link.id) {
        ids.add(item.link.id);
      }
      if (Array.isArray(item.items)) {
        scanCurated(item.items, ids, autogenDirs);
      }
    }
  }
}

/** All doc-ids on disk for the active language (relative path without .md). */
function scanDiskDocIds(docsDir) {
  /** @type {string[]} */
  const out = [];
  if (!fs.existsSync(docsDir)) return out;
  /** @param {string} dir */
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
      } else if (entry.isFile() && entry.name.endsWith('.md')) {
        const rel = path.relative(docsDir, full).replace(/\\/g, '/');
        out.push(rel.replace(/\.md$/, ''));
      }
    }
  };
  walk(docsDir);
  return out;
}

function appendUnlisted() {
  try {
    const ids = new Set();
    const autogenDirs = new Set();
    scanCurated(sidebars.wikiSidebar, ids, autogenDirs);

    const docsDir = isEN ? 'docs-en' : 'docs';
    const onDisk = scanDiskDocIds(docsDir);

    const isCovered = (id) => {
      if (ids.has(id)) return true;
      for (const dir of autogenDirs) {
        if (id === dir || id.startsWith(dir + '/')) return true;
      }
      return false;
    };

    const unlisted = onDisk
      .filter((id) => !isCovered(id))
      .sort((a, b) => a.localeCompare(b));

    if (unlisted.length > 0) {
      sidebars.wikiSidebar.push({
        type: 'category',
        label: t('Overig', 'More'),
        collapsed: false,
        items: unlisted.map((id) => ({type: 'doc', id})),
      });
    }
  } catch {
    // If anything goes wrong scanning, fall back to the curated sidebar as-is.
  }
}

appendUnlisted();

